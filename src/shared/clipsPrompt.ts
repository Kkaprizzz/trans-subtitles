/** Промпт выбора клипов. Хранится отдельно от логики: его будем подбирать по результатам на реальных подкастах. */
import type { TextWindow } from './clips.ts'

export interface ChatMessage {
  role: 'system' | 'user' | 'assistant'
  content: string
}

export interface PromptOpts {
  minDur: number
  maxDur: number
}

export const PROMPT_VERSION = 2

export function systemPrompt(o: PromptOpts): string {
  return `Ты монтажёр коротких вертикальных видео (Shorts, Reels, TikTok) и работаешь с расшифровкой русскоязычного подкаста. Выбери фрагменты, которые хорошо работают как самостоятельные ролики.

Расшифровка машинная: без знаков препинания и заглавных букв, с ошибками распознавания, реплики разных людей не разделены. Она разбита на куски по ~10 секунд вида «[S12 03:05-03:21] текст»: S12 — номер куска, дальше время его начала и конца в записи. Границы кусков случайные и могут проходить посреди фразы.

Хороший фрагмент:
- законченная мысль или история: понятна без остального выпуска, есть начало и завершение;
- начинается сильной фразой (тезис, вопрос, неожиданное утверждение, конфликт), а не словами «ну», «так вот», приветствием или отсылкой к сказанному раньше;
- несёт ценность зрителю: инсайт, эмоция, спор, конкретный совет, смешной момент, сильная история;
- длится от ${o.minDur} до ${o.maxDur} секунд по таймкодам.

Не выбирай: представление гостей, рекламные интеграции, организационные фразы, подводки, пустую болтовню.

Границы фрагмента:
- start_segment — кусок, где фрагмент начинается, end_segment — кусок, где он заканчивается;
- start_words — первые 4–6 слов фрагмента, end_words — последние 4–6 слов. Копируй их из текста ДОСЛОВНО, как они записаны, включая ошибки распознавания; не исправляй и не пересказывай;
- фрагмент начинается с начала фразы и заканчивается её концом, даже если для этого он начинается или кончается посреди куска.

Ответ — только JSON, без пояснений вокруг:
{"clips":[{"start_segment":12,"start_words":"а ты знаешь почему","end_segment":19,"end_words":"вот так это и работает","score":8,"title":"...","reason":"...","description":"...","hashtags":["...","..."],"overlay_after_segment":15,"overlay_after_words":"и тут всё стало понятно"}]}

Поля:
- score: от 1 до 10, насколько фрагмент зацепит зрителя;
- title: до 60 символов, цепляющий заголовок без обмана, нормальным русским языком;
- reason: одна фраза, почему выбран именно этот фрагмент;
- description: 1–2 предложения для подписи под видео;
- hashtags: 3–6 хэштегов на русском, без символа #;
- overlay_after_segment и overlay_after_words: место внутри фрагмента для рекламной вставки — кусок и 3–5 слов дословно, сразу после которых естественная пауза (закончилась мысль). Не в первые и не в последние 5 секунд фрагмента. Если такого места нет — null для обоих.

Если в части выпуска нет подходящих фрагментов, верни {"clips":[]}. Используй только номера кусков и слова из текста, ничего не выдумывай.`
}

export function userPrompt(w: TextWindow, total: number, count: number): string {
  const part = total > 1 ? `Это часть ${w.index + 1} из ${total} длинного выпуска, куски S${w.firstSeg}–S${w.lastSeg}. ` : ''
  return `${part}Выбери до ${count} лучших фрагментов.\n\n${w.text}`
}

export function retryPrompt(reason: string): string {
  return `Ответ не удалось разобрать (${reason}). Верни только корректный JSON указанного формата, без текста вокруг и без markdown.`
}
